// Regenerates src/server/services/mcp/vibrationMonitorSource.ts from
// vibration_monitor.py. The .py is the file a CircuitPython board runs as
// code.py; the server spawns the embedded copy (packaged builds carry no
// loose .py files). tests/vibrationProtocol.test.ts fails while they differ.
//
//     node build/embed-vibration-monitor.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'server', 'services', 'mcp');
const source = fs.readFileSync(path.join(dir, 'vibration_monitor.py'), 'utf8').replace(/\r\n/g, '\n');
if (source.includes('`') || source.includes('${')) {
    throw new Error('vibration_monitor.py must not contain a backtick or "${" (it is embedded in a template literal)');
}
const out = [
    '// GENERATED by build/embed-vibration-monitor.js from vibration_monitor.py - do not edit;',
    '// edit the .py and re-run the script (tests/vibrationProtocol.test.ts checks they match).',
    '/* eslint-disable */',
    `export const VIBRATION_MONITOR_SOURCE = String.raw\`${source}\`;`,
    '',
].join('\n');
fs.writeFileSync(path.join(dir, 'vibrationMonitorSource.ts'), out);
console.log(`vibrationMonitorSource.ts: ${source.length} characters`);
